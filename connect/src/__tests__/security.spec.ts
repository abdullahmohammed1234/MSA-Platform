import test from 'node:test';
import assert from 'node:assert/strict';
import {
  isValidQrImageSource,
  isValidExternalCalendarUrl,
  sanitizeRedirectPath,
} from '../utils/security.ts';

test('QR Image Validation — Backend Contract Compliance (Strict PNG Only)', async (t) => {
  await t.test('accepts valid raster PNG data URI generated by backend QrCodeGenerator', () => {
    // Genuine 64+ char base64 string starting with PNG magic bytes (iVBOR)
    const validPng = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAARgAAAEUAQMAAAB+55n2AAAABlBMVEX///8AAABVwtN+AAAAAXRSTlMAQObYZgAAAFtJREFUeN7t1yEOwDAMBDH4';
    assert.equal(isValidQrImageSource(validPng), true);
  });

  await t.test('strictly rejects JPEG data URIs — backend contract exclusively requires PNG', () => {
    const validJpeg = 'data:image/jpeg;base64,/9j/4AAQSkZJRgABAQEASABIAAD/2wBDAP//////////////////////////////////////////////////////////////////////////////////////wgALCAEUAQMBEQ/8QAFBABAAAAAAAAAAAAAAAAAAAAAP/aAAgBAQABPxA=';
    assert.equal(isValidQrImageSource(validJpeg), false);
  });

  await t.test('strictly rejects SVG data URIs to prevent embedded script injection', () => {
    const maliciousSvg = 'data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>';
    assert.equal(isValidQrImageSource(maliciousSvg), false);
  });

  await t.test('strictly rejects arbitrary data URIs (e.g. data:text/html)', () => {
    assert.equal(isValidQrImageSource('data:text/html;base64,PHNjcmlwdD5hbGVydCgxKTwvc2NyaXB0Pg=='), false);
    assert.equal(isValidQrImageSource('data:application/javascript;base64,YWxlcnQoMSk='), false);
  });

  await t.test('rejects arbitrary external URLs to avoid tracking or mixed-content leakage', () => {
    assert.equal(isValidQrImageSource('https://tracker.external.com/qr.png'), false);
    assert.equal(isValidQrImageSource('http://insecure.org/ticket-qr'), false);
  });

  await t.test('rejects javascript: and file: schemes', () => {
    assert.equal(isValidQrImageSource('javascript:alert(document.cookie)'), false);
    assert.equal(isValidQrImageSource('file:///etc/passwd'), false);
  });

  await t.test('rejects non-PNG base64 payloads even if exceeding length threshold', () => {
    // 80 characters of valid base64 but lacking PNG magic signature 'iVBOR'
    const fakePayload = 'data:image/png;base64,' + 'A'.repeat(80);
    assert.equal(isValidQrImageSource(fakePayload), false);
  });

  await t.test('rejects malformed Base64 formatting and padding corruption', () => {
    // Padding in the middle
    assert.equal(isValidQrImageSource('data:image/png;base64,iVBORw0K=abc=123456789012345678901234567890123456789012345678901234'), false);
    // Invalid characters
    assert.equal(isValidQrImageSource('data:image/png;base64,iVBORw0K!@#$%^&*()12345678901234567890123456789012345678901234567890'), false);
    // Invalid padding (3 equals)
    assert.equal(isValidQrImageSource('data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAARgAAAEUAQMAAAB+55n2AAAABlBMVEX///8AAABVwtN+==='), false);
  });

  await t.test('rejects null, undefined, empty, and truncated payloads', () => {
    assert.equal(isValidQrImageSource(null), false);
    assert.equal(isValidQrImageSource(undefined), false);
    assert.equal(isValidQrImageSource(''), false);
    assert.equal(isValidQrImageSource('data:image/png;base64,short'), false);
  });
});

test('External Calendar URL Validation', async (t) => {
  await t.test('accepts genuine Google Calendar compose URLs', () => {
    const googleUrl = 'https://calendar.google.com/calendar/render?action=TEMPLATE&text=Welcome+Night&dates=20261014T180000Z/20261014T200000Z';
    assert.equal(isValidExternalCalendarUrl(googleUrl), true);
  });

  await t.test('accepts genuine Outlook.com calendar compose URLs', () => {
    const outlookUrl = 'https://outlook.live.com/calendar/0/deeplink/compose?path=/calendar/action/compose&rru=addevent&subject=Meeting';
    assert.equal(isValidExternalCalendarUrl(outlookUrl), true);
  });

  await t.test('accepts genuine Yahoo Calendar compose URLs', () => {
    const yahooUrl = 'https://calendar.yahoo.com/?v=60&view=d&type=20&title=Jumuah';
    assert.equal(isValidExternalCalendarUrl(yahooUrl), true);
  });

  await t.test('rejects non-HTTPS schemes even for calendar domains', () => {
    assert.equal(isValidExternalCalendarUrl('http://calendar.google.com/render'), false);
  });

  await t.test('rejects untrusted third-party hostnames', () => {
    assert.equal(isValidExternalCalendarUrl('https://phishing-calendar.com/compose'), false);
    assert.equal(isValidExternalCalendarUrl('https://google.com.attacker.com/calendar'), false);
    assert.equal(isValidExternalCalendarUrl('https://evil.org/?q=https://calendar.google.com'), false);
  });

  await t.test('rejects embedded credentials in calendar URLs', () => {
    assert.equal(isValidExternalCalendarUrl('https://victim:secret@calendar.google.com/render'), false);
    assert.equal(isValidExternalCalendarUrl('https://attacker@outlook.live.com/calendar'), false);
  });

  await t.test('rejects non-standard ports on calendar hosts', () => {
    assert.equal(isValidExternalCalendarUrl('https://calendar.google.com:8443/render'), false);
  });

  await t.test('rejects dangerous protocols', () => {
    assert.equal(isValidExternalCalendarUrl('javascript:window.open("https://calendar.google.com")'), false);
    assert.equal(isValidExternalCalendarUrl('data:text/html,<a href="https://calendar.google.com">Cal</a>'), false);
  });
});

test('Redirect Path Sanitization — Open Redirect Protection', async (t) => {
  await t.test('allows safe internal application paths', () => {
    assert.equal(sanitizeRedirectPath('/app/dashboard'), '/app/dashboard');
    assert.equal(sanitizeRedirectPath('/app/events/welcome-night'), '/app/events/welcome-night');
    assert.equal(sanitizeRedirectPath('/app/tickets?status=active'), '/app/tickets?status=active');
  });

  await t.test('defuses protocol-relative URL attacks (//attacker.com)', () => {
    assert.equal(sanitizeRedirectPath('//attacker.com/steal-session'), '/app/dashboard');
  });

  await t.test('defuses backslash URL evasion (/\\attacker.com)', () => {
    assert.equal(sanitizeRedirectPath('/\\attacker.com'), '/app/dashboard');
    assert.equal(sanitizeRedirectPath('/app\\dashboard'), '/app/dashboard');
  });

  await t.test('defuses absolute HTTP/HTTPS redirection', () => {
    assert.equal(sanitizeRedirectPath('https://evil.com'), '/app/dashboard');
    assert.equal(sanitizeRedirectPath('http://malicious.org'), '/app/dashboard');
  });

  await t.test('defuses slash-prefixed scheme evasion (/https://evil.com, /javascript:...)', () => {
    assert.equal(sanitizeRedirectPath('/https://evil.com/app'), '/app/dashboard');
    assert.equal(sanitizeRedirectPath('/javascript:alert(1)'), '/app/dashboard');
  });

  await t.test('defuses control characters and linebreaks in paths', () => {
    assert.equal(sanitizeRedirectPath('/app/dashboard\r\nSet-Cookie:bad=1'), '/app/dashboard');
    assert.equal(sanitizeRedirectPath('/app/dashboard\x00evil'), '/app/dashboard');
  });

  await t.test('falls back safely for null, undefined, and empty string', () => {
    assert.equal(sanitizeRedirectPath(null), '/app/dashboard');
    assert.equal(sanitizeRedirectPath(undefined), '/app/dashboard');
    assert.equal(sanitizeRedirectPath(''), '/app/dashboard');
  });
});
